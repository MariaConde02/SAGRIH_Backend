-- SAGRIH - Esquema de Base de Datos PostgreSQL

-- TM_ROLES
CREATE TABLE IF NOT EXISTS TM_ROLES (
    ROLES_ID    SERIAL PRIMARY KEY,
    ROLES_NM    VARCHAR(50)  NOT NULL UNIQUE,
    ROLES_DS    VARCHAR(255)
);

-- TM_PERMI
CREATE TABLE IF NOT EXISTS TM_PERMI (
    PERMI_ID    SERIAL PRIMARY KEY,
    PERMI_NM    VARCHAR(100) NOT NULL UNIQUE,
    PERMI_DS    VARCHAR(255)
);

-- TM_UNIDM
CREATE TABLE IF NOT EXISTS TM_UNIDM (
    UNIDM_ID    SERIAL PRIMARY KEY,
    UNIDM_NM    VARCHAR(50)  NOT NULL UNIQUE,
    UNIDM_AB    VARCHAR(10)  NOT NULL
);

-- TM_TIPOD
CREATE TABLE IF NOT EXISTS TM_TIPOD (
    TIPOD_ID    SERIAL PRIMARY KEY,
    TIPOD_NM    VARCHAR(100) NOT NULL UNIQUE
);

-- TM_CULTI
CREATE TABLE IF NOT EXISTS TM_CULTI (
    CULTI_ID    SERIAL PRIMARY KEY,
    CULTI_NM    VARCHAR(100) NOT NULL UNIQUE,
    CULTI_MI    NUMERIC(5,2),
    CULTI_MA    NUMERIC(5,2)
);

-- TM_TIPAL
CREATE TABLE IF NOT EXISTS TM_TIPAL (
    TIPAL_ID    SERIAL PRIMARY KEY,
    TIPAL_NM    VARCHAR(50)  NOT NULL UNIQUE,
    TIPAL_DS    VARCHAR(255)
);

-- TM_INVER
CREATE TABLE IF NOT EXISTS TM_INVER (
    INVER_ID    VARCHAR(20) PRIMARY KEY,
    INVER_NM    VARCHAR(100) NOT NULL,
    INVER_UB    VARCHAR(255),
    INVER_EST   VARCHAR(20) DEFAULT 'activo',
    INVER_MA    BOOLEAN DEFAULT FALSE,
    INVER_FC    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INVER_AN    NUMERIC(10,2),
    INVER_LA    NUMERIC(10,2),
    INVER_PA    NUMERIC(5,2)
);

-- TM_USUAR
CREATE TABLE IF NOT EXISTS TM_USUAR (
    USUAR_ID    SERIAL PRIMARY KEY,
    USUAR_NM    VARCHAR(100) NOT NULL,
    USUAR_AP    VARCHAR(100),
    USUAR_EM    VARCHAR(150) NOT NULL UNIQUE,
    USUAR_PW    VARCHAR(255) NOT NULL,
    USUAR_MN    VARCHAR(20) DEFAULT 'email',
    USUAR_TI    VARCHAR(100),
    ROLES_ID    INTEGER REFERENCES TM_ROLES(ROLES_ID),
    USUAR_FC    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    USUAR_AT    TIMESTAMP,
    USUAR_EST   VARCHAR(20) DEFAULT 'activo'
);

-- TM_CANTE
CREATE TABLE IF NOT EXISTS TM_CANTE (
    CANTE_ID    VARCHAR(10) PRIMARY KEY,
    CANTE_NM    VARCHAR(100) NOT NULL,
    INVER_ID    VARCHAR(20) REFERENCES TM_INVER(INVER_ID) ON DELETE CASCADE,
    CULTI_ID    INTEGER REFERENCES TM_CULTI(CULTI_ID),
    CANTE_MI    NUMERIC(5,2),
    CANTE_MA    NUMERIC(5,2)
);

-- TT_ROLPE
CREATE TABLE IF NOT EXISTS TT_ROLPE (
    ROLPE_ID    SERIAL PRIMARY KEY,
    ROLES_ID    INTEGER NOT NULL REFERENCES TM_ROLES(ROLES_ID) ON DELETE CASCADE,
    PERMI_ID    INTEGER NOT NULL REFERENCES TM_PERMI(PERMI_ID) ON DELETE CASCADE,
    UNIQUE(ROLES_ID, PERMI_ID)
);

-- TT_DISPO
CREATE TABLE IF NOT EXISTS TT_DISPO (
    DISPO_ID    VARCHAR(20) PRIMARY KEY,
    DISPO_TG    VARCHAR(100),
    TIPOD_ID    INTEGER NOT NULL REFERENCES TM_TIPOD(TIPOD_ID),
    CANTE_ID    VARCHAR(10) REFERENCES TM_CANTE(CANTE_ID) ON DELETE SET NULL,
    INVER_ID    VARCHAR(20) REFERENCES TM_INVER(INVER_ID) ON DELETE CASCADE,
    DISPO_ET    VARCHAR(20) DEFAULT 'Operativo',
    DISPO_SM    BOOLEAN DEFAULT FALSE,
    DISPO_FC    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- TT_LECTU
CREATE TABLE IF NOT EXISTS TT_LECTU (
    LECTU_ID    SERIAL PRIMARY KEY,
    DISPO_ID    VARCHAR(20) NOT NULL REFERENCES TT_DISPO(DISPO_ID) ON DELETE CASCADE,
    LECTU_VL    NUMERIC(10,2) NOT NULL,
    UNIDM_ID    INTEGER NOT NULL REFERENCES TM_UNIDM(UNIDM_ID),
    LECTU_FH    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_lectu_dispo_fh ON TT_LECTU(DISPO_ID, LECTU_FH DESC);

-- TT_PROGR
CREATE TABLE IF NOT EXISTS TT_PROGR (
    PROGR_ID    SERIAL PRIMARY KEY,
    CANTE_ID    VARCHAR(10) NOT NULL REFERENCES TM_CANTE(CANTE_ID) ON DELETE CASCADE,
    PROGR_HI    TIME NOT NULL,
    PROGR_DR    INTEGER NOT NULL,
    PROGR_AT    BOOLEAN DEFAULT TRUE,
    PROGR_FC    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_progr_cante ON TT_PROGR(CANTE_ID);

-- TT_PROGD
CREATE TABLE IF NOT EXISTS TT_PROGD (
    PROGD_ID    SERIAL PRIMARY KEY,
    PROGR_ID    INTEGER NOT NULL REFERENCES TT_PROGR(PROGR_ID) ON DELETE CASCADE,
    PROGD_DA    INTEGER NOT NULL CHECK (PROGD_DA BETWEEN 1 AND 7),
    UNIQUE(PROGR_ID, PROGD_DA)
);

-- TT_ALERT
CREATE TABLE IF NOT EXISTS TT_ALERT (
    ALERT_ID    SERIAL PRIMARY KEY,
    DISPO_ID    VARCHAR(20) REFERENCES TT_DISPO(DISPO_ID) ON DELETE SET NULL,
    TIPAL_ID    INTEGER NOT NULL REFERENCES TM_TIPAL(TIPAL_ID),
    ALERT_TI    VARCHAR(255),
    ALERT_FD    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ALERT_EA    VARCHAR(20) DEFAULT 'activa'
);
CREATE INDEX IF NOT EXISTS idx_alert_ea ON TT_ALERT(ALERT_EA);

-- TT_LOGCO
CREATE TABLE IF NOT EXISTS TT_LOGCO (
    LOGCO_ID    SERIAL PRIMARY KEY,
    DISPO_ID    VARCHAR(20) NOT NULL REFERENCES TT_DISPO(DISPO_ID) ON DELETE CASCADE,
    LOGCO_EV    VARCHAR(50) NOT NULL,
    LOGCO_FH    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_logco_dispo_fh ON TT_LOGCO(DISPO_ID, LOGCO_FH DESC);

-- TP_PARAM
CREATE TABLE IF NOT EXISTS TP_PARAM (
    PARAM_ID    SERIAL PRIMARY KEY,
    PARAM_CL    VARCHAR(100) NOT NULL UNIQUE,
    PARAM_VL    VARCHAR(255) NOT NULL,
    PARAM_DS    VARCHAR(255),
    PARAM_UM    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PARAM_IU    INTEGER REFERENCES TM_USUAR(USUAR_ID)
);

-- TH_RIHRI
CREATE TABLE IF NOT EXISTS TH_RIHRI (
    RIHRI_ID    SERIAL PRIMARY KEY,
    CANTE_ID    VARCHAR(10) NOT NULL REFERENCES TM_CANTE(CANTE_ID) ON DELETE CASCADE,
    RIHRI_TA    VARCHAR(20) DEFAULT 'Automático',
    RIHRI_FI    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RIHRI_FF    TIMESTAMP,
    RIHRI_VL    NUMERIC(10,2),
    PROGR_ID    INTEGER REFERENCES TT_PROGR(PROGR_ID) ON DELETE SET NULL,
    USUAR_ID    INTEGER REFERENCES TM_USUAR(USUAR_ID)
);
CREATE INDEX IF NOT EXISTS idx_rihri_cante_fi ON TH_RIHRI(CANTE_ID, RIHRI_FI DESC);

-- TH_MANTE
CREATE TABLE IF NOT EXISTS TH_MANTE (
    MANTE_ID    SERIAL PRIMARY KEY,
    DISPO_ID    VARCHAR(20) REFERENCES TT_DISPO(DISPO_ID) ON DELETE SET NULL,
    MANTE_TA    VARCHAR(100) NOT NULL,
    MANTE_FE    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    MANTE_OB    TEXT,
    USUAR_ID    INTEGER REFERENCES TM_USUAR(USUAR_ID),
    MANTE_RE    BOOLEAN DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_mante_dispo ON TH_MANTE(DISPO_ID);

-- Trigger para actualizar PARAM_UM
CREATE OR REPLACE FUNCTION fn_update_param_um()
RETURNS TRIGGER AS $$
BEGIN
    NEW.PARAM_UM = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_param_um ON TP_PARAM;
CREATE TRIGGER trg_param_um
    BEFORE UPDATE ON TP_PARAM
    FOR EACH ROW
    EXECUTE FUNCTION fn_update_param_um();
